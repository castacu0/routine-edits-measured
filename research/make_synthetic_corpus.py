#!/usr/bin/env python3
"""
Procedurally generated smoke-test corpus.

    python research/make_synthetic_corpus.py --out ~/datasets/vd-synthetic --n 1000

Writes N deterministic images (gradient background + Gaussian noise + 3–7
geometric shapes) to a directory that MUST be outside this repository. Every
image is reproducible from (seed, index), so a result computed on it can be
regenerated by anyone without transferring a single file.

WHAT THIS CORPUS IS FOR
-----------------------
  - proving the harness runs end to end;
  - the hash-stability regression (research/regression.py uses the same idea);
  - reproducing, on identical inputs, any number somebody computed on a
    "synthetic" corpus of this kind, so the comparison is like for like.

WHAT IT IS NOT FOR
------------------
  Any claim about error rates or robustness of a perceptual hash on real
  content. These images have no natural 1/f spectrum, no texture and no
  repetition, so their DCT statistics are nothing like a photograph's. See the
  "Do not cite the smoke-test numbers" box in research/README.md. Run the
  same protocol on a benign photographic corpus before reporting a number.

No image produced here is ever written inside the repository: the script
refuses an output path under the repo root, mirroring run.py's corpus guard.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

REPO = Path(__file__).resolve().parents[1]


def guard_out(path: Path) -> None:
    resolved = path.resolve()
    try:
        resolved.relative_to(REPO)
    except ValueError:
        return
    raise SystemExit(
        "✖ Output directory must be OUTSIDE this repository.\n"
        "  No image dataset belongs in a zero-custody repo, benign or not."
    )


def make_image(seed: int, index: int, width: int = 640, height: int = 480) -> Image.Image:
    """
    One deterministic image. Uses numpy's Generator with an explicit seed
    derived from (seed, index) so the corpus is stable across runs and across
    machines with the same numpy major version.
    """
    rng = np.random.default_rng([seed, index])

    # Randomised linear gradient background between two colours.
    c0 = rng.integers(0, 256, size=3).astype(np.float32)
    c1 = rng.integers(0, 256, size=3).astype(np.float32)
    angle = rng.uniform(0, 2 * np.pi)
    yy, xx = np.mgrid[0:height, 0:width].astype(np.float32)
    t = (xx * np.cos(angle) + yy * np.sin(angle))
    t = (t - t.min()) / max(1e-6, float(t.max() - t.min()))
    bg = c0[None, None, :] * (1 - t[..., None]) + c1[None, None, :] * t[..., None]

    # Additive Gaussian noise, moderate sigma.
    bg = bg + rng.normal(0.0, 6.0, size=bg.shape).astype(np.float32)
    img = Image.fromarray(np.clip(bg, 0, 255).astype(np.uint8), "RGB")

    # 3–7 superimposed shapes: ellipse, rectangle or polygon.
    d = ImageDraw.Draw(img)
    for _ in range(int(rng.integers(3, 8))):
        colour = tuple(int(v) for v in rng.integers(0, 256, size=3))
        w = int(rng.integers(40, width // 2))
        h = int(rng.integers(40, height // 2))
        x0 = int(rng.integers(-w // 4, width - w // 2))
        y0 = int(rng.integers(-h // 4, height - h // 2))
        kind = int(rng.integers(0, 3))
        if kind == 0:
            d.ellipse([x0, y0, x0 + w, y0 + h], fill=colour)
        elif kind == 1:
            d.rectangle([x0, y0, x0 + w, y0 + h], fill=colour)
        else:
            k = int(rng.integers(3, 7))
            pts = [(int(x0 + rng.integers(0, w + 1)), int(y0 + rng.integers(0, h + 1))) for _ in range(k)]
            d.polygon(pts, fill=colour)
    return img


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True, type=Path, help="output directory, OUTSIDE this repository")
    ap.add_argument("--n", type=int, default=1000)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--size", default="640x480", help="WxH, default 640x480")
    ap.add_argument("--format", choices=["png", "jpg"], default="png",
                    help="png keeps the original lossless so JPEG is a transformation, not a baseline")
    args = ap.parse_args()

    guard_out(args.out)
    w, h = (int(v) for v in args.size.lower().split("x"))
    args.out.mkdir(parents=True, exist_ok=True)

    started = time.time()
    for i in range(args.n):
        img = make_image(args.seed, i, w, h)
        img.save(args.out / f"syn_{args.seed}_{i:06d}.{args.format}",
                 **({"quality": 95} if args.format == "jpg" else {}))
        if i % 200 == 0:
            print(f"\r  {i}/{args.n}", end="", flush=True)
    print(f"\r  {args.n}/{args.n}")

    manifest = {
        "generator": "research/make_synthetic_corpus.py",
        "kind": "procedural: gradient + gaussian noise + 3-7 shapes",
        "seed": args.seed, "n": args.n, "size": [w, h], "format": args.format,
        "numpy": np.__version__, "generated": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "warning": "smoke-test corpus; not photographs; do not cite rates computed on it",
    }
    (args.out / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"✔ {args.n} images written to {args.out} in {time.time() - started:.1f}s "
          f"(manifest: MANIFEST.json)")


if __name__ == "__main__":
    sys.exit(main())
